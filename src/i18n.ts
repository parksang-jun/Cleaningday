const DICTS: Record<Lang, Dict> = { en, ko, ja };
export type StrKey = keyof Dict;

let current: Lang = 'en';

export function detectLang(pref: 'auto' | Lang): Lang {
  if (pref !== 'auto') return pref;
  const n = (typeof navigator !== 'undefined' ? navigator.language : 'en').toLowerCase();
  if (n.startsWith('ko')) return 'ko';
  if (n.startsWith('ja')) return 'ja';
  return 'en';
}

export function setLang(l: Lang): void {
  current = l;
  if (typeof document !== 'undefined') document.documentElement.lang = l;
}

export function getLang(): Lang {
  return current;
}

export function t(key: StrKey | string, params?: Record<string, string | number>): string {
  const d = DICTS[current] as Record<string, string>;
  let s = d[key] ?? (en as Record<string, string>)[key] ?? key;
  if (params) for (const [k, v] of Object.entries(params)) s = s.replace(`{${k}}`, String(v));
  return s;
}

export function allKeysMatch(): boolean {
  const base = Object.keys(en).sort().join(',');
  return Object.keys(ko).sort().join(',') === base && Object.keys(ja).sort().join(',') === base;
}
